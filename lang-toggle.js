document.addEventListener("DOMContentLoaded", function () {
    const langToggleContainer = document.createElement("div");
    langToggleContainer.id = "lang-toggle-container";
    langToggleContainer.innerHTML = `
        <button class="lang-btn" data-lang="id">ID</button>
        <button class="lang-btn" data-lang="en">EN</button>
        <button class="lang-btn" data-lang="ko">KR</button>
    `;
    document.body.appendChild(langToggleContainer);

    // Style the container dynamically if not in CSS
    Object.assign(langToggleContainer.style, {
        position: "fixed",
        top: "20px",
        right: "20px",
        zIndex: "1000",
        background: "rgba(238, 242, 238, 0.9)", // Light gray/greenish tint match
        padding: "4px",
        borderRadius: "50px",
        boxShadow: "0 2px 10px rgba(0,0,0,0.05)",
        display: "flex",
        gap: "0px",
        backdropFilter: "blur(5px)"
    });

    const buttons = langToggleContainer.querySelectorAll(".lang-btn");
    buttons.forEach(btn => {
        Object.assign(btn.style, {
            border: "none",
            background: "transparent",
            cursor: "pointer",
            padding: "4px 12px",
            borderRadius: "20px",
            fontWeight: "700",
            fontSize: "0.75rem",
            color: "#666",
            transition: "all 0.3s",
            fontFamily: "'Inter', sans-serif"
        });

        btn.addEventListener("click", () => {
            setLanguage(btn.dataset.lang);
        });
    });

    // Load saved language
    const savedLang = localStorage.getItem("selectedLang") || "id";
    setLanguage(savedLang);
});

function setLanguage(lang) {
    localStorage.setItem("selectedLang", lang);
    document.documentElement.lang = lang; // Update HTML lang attribute

    // Update active button state
    document.querySelectorAll(".lang-btn").forEach(btn => {
        if (btn.dataset.lang === lang) {
            btn.style.background = "#1A4026";
            btn.style.color = "white";
        } else {
            btn.style.background = "transparent";
            btn.style.color = "#1A4026";
        }
    });

    // Translate content
    const elements = document.querySelectorAll("[data-i18n]");
    elements.forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (translations[lang] && translations[lang][key]) {
            // Check if element has children tags (like strong)
            if (el.children.length > 0 && translations[lang][key].includes("<")) {
                el.innerHTML = translations[lang][key];
            } else if (el.tagName === "IMG") {
                // skip images unless alt text translation needed
            } else {
                // If the translation contains HTML, use innerHTML, otherwise textContent
                // To be safe, specific keys known to have HTML (bold tags) use innerHTML
                if (translations[lang][key].includes("<")) {
                    el.innerHTML = translations[lang][key];
                } else {
                    el.innerText = translations[lang][key];
                }
            }
        }
    });
}
